# numpy의 ndarray는 단순한 배열이라기 보다,
# 벡터/행열 연산도 가능한 다차원 수치 데이터 구조다
import numpy as np
# numpy 라이브러리를 np라는 짧은 이름으로 불러옴
# 앞으로 numpy 대신 np로 간단하게 사용 가능

ss = ['tom', 'james', 'oscar', 1, True]
# 문자열, 숫자, 불리언이 섞여 있는 일반 파이썬 리스트 생성

print(ss, ' ', type(ss))
# ss의 내용과 자료형 출력
# 결과: 리스트 내용 / <class 'list'>

ss2 = np.array(ss)   # 같은 type의 자료로만 구성
# 리스트 ss를 numpy 배열로 변환
# 주의:
# numpy 배열은 원래 같은 자료형으로 맞춰서 저장하려는 성질이 있음
# 지금은 문자열, 숫자, True가 섞여 있으므로
# numpy가 전부 하나의 자료형으로 통일해서 저장함
# 보통 이런 경우 문자열 쪽으로 맞춰질 가능성이 큼

print(ss2, ' ', type(ss2))
# numpy 배열의 내용과 자료형 출력
# 결과: 배열 내용 / <class 'numpy.ndarray'>

li = list(range(1, 10))
# 1부터 9까지의 숫자를 가지는 리스트 생성
# 결과: [1, 2, 3, 4, 5, 6, 7, 8, 9]

print(li)
# 리스트 전체 출력

print(li[0], ' ', id(li[0]))
# li의 첫 번째 값 출력
# id(li[0])는 그 값이 저장된 메모리 주소(고유 번호 비슷한 것)를 보여줌

print(li * 10)
# 리스트를 10번 반복해서 이어붙인 결과 출력
# 곱셈이 "각 원소에 10을 곱하는 것"이 아니라
# "리스트 자체를 10번 반복"하는 뜻임

print("---" * 10)
# "---" 문자열을 10번 반복해서 구분선처럼 출력

for i in li:
    print(i * 10, end=' ')
# 리스트의 각 원소를 하나씩 꺼내서 10을 곱해 출력
# end=' ' 는 줄바꿈 대신 옆으로 띄어쓰기 하면서 출력
# 결과: 10 20 30 40 50 60 70 80 90

num_arr = np.array(li)
# 파이썬 리스트 li를 numpy 배열로 변환
# 이제 숫자 계산에 더 적합한 구조가 됨

print(num_arr[0], ' ', num_arr[1], ' ', id(num_arr[0]), ' ', id(num_arr[1]))
# numpy 배열의 첫 번째, 두 번째 값 출력
# 그리고 각각의 id도 출력
# numpy 배열의 원소는 파이썬 기본 int와 조금 다르게 numpy 자료형일 수 있음

print(num_arr * 10)  # 벡터화 연산이 가능 

print()
a = np.array([1, 2, 3.5], dtype='float32')
print(a, type(a))   # ndarray는 동일 타입만 취급
# 여러 타입의 자료가 입력되면 상위 타입으로 장동변환. int -> float -> complex -> str

print()
print()
# 빈 줄 출력
# 보기 좋게 출력 결과를 한 칸 띄우는 역할

b = np.array([[1, 2, 3], [4, 5, 6]])
# 2행 3열짜리 numpy 배열 생성
# 모양:
# [[1 2 3]
#  [4 5 6]]

print(b, b.shape, ' ', b[0, 0], ' ', b[[0]])
# b        : 배열 전체 출력
# b.shape  : 배열의 모양 출력 -> (2, 3) = 2행 3열
# b[0, 0]  : 0행 0열 값 출력 -> 1
# b[[0]]   : 0번 행을 2차원 배열 모양 유지해서 가져옴 -> [[1 2 3]]

print()
# 빈 줄 출력

c = np.zeros((2, 2))
# 2행 2열짜리 배열을 만들고
# 모든 값을 0으로 채움
# 결과:
# [[0. 0.]
#  [0. 0.]]

print(c)
# c 배열 출력

d = np.ones((2, 2))
# 2행 2열짜리 배열을 만들고
# 모든 값을 1로 채움
# 결과:
# [[1. 1.]
#  [1. 1.]]

print(d)
# d 배열 출력

e = np.eye(3)
# 3행 3열 단위행렬(identity matrix) 생성
# 대각선만 1이고 나머지는 0
# 결과:
# [[1. 0. 0.]
#  [0. 1. 0.]
#  [0. 0. 1.]]

print(e)
# e 배열 출력

print()
# 빈 줄 출력

print(np.random.rand(5))   # 균등 분포
# 0 이상 1 미만 사이의 랜덤한 숫자 5개 생성
# 숫자가 고르게 나올 가능성이 있는 방식
# 예: [0.23 0.81 0.44 0.12 0.67]

print(np.random.randn(5))   # 정규 분포
# 평균 0, 표준편차 1을 기준으로 랜덤한 숫자 5개 생성
# 0 근처 값이 많이 나오고 큰 값은 드물게 나옴
# 예: [-0.25 1.13 0.44 -1.52 0.08]

np.random.seed(0)
# 랜덤 숫자를 만들 때 기준값(시드값)을 0으로 고정
# 이렇게 하면 실행할 때마다 항상 같은 랜덤 결과가 나옴
# 즉, "랜덤처럼 보이지만 재현 가능하게" 만드는 것

print(np.random.randn(2, 3))
# randn : 정규분포를 따르는 랜덤 숫자를 생성
# (2, 3)은 2행 3열 모양으로 만들라는 뜻
# 즉, 랜덤 숫자 6개를 뽑아서 2행 3열 배열로 만듦

print(list(range(0, 10)))
print(np.arange(10))

print()
# 인덱싱/슬라이싱
a = np.array([1,2,3,4,5])
print(a, ' ', a[1])
print(a[1:4])    
# a의 인덱스 1번부터 4번 전까지 가져옴
# 시작값은 포함, 끝값은 포함하지 않음
# 즉 1번, 2번, 3번 요소를 출력

print(a[1:])
# a의 인덱스 1번부터 끝까지 가져옴
# 즉 두 번째 요소부터 마지막 요소까지 출력

print(a[1:5:2])
# a의 인덱스 1번부터 5번 전까지 가져오는데
# 2칸씩 건너뛰면서 가져옴
# 즉 1번, 3번 요소를 출력

print(a[-2:])
# a의 뒤에서 두 번째 요소부터 끝까지 가져옴
# 음수 인덱스는 뒤에서부터 셈
# -1은 마지막 요소, -2는 뒤에서 두 번째 요소

# 주소 치환
b = a
print(a[0], ' ', b[0])
b[0] = 88
print(a[0], ' ', b[0])
c = np.copy(a)  # 복사본 생성
print(a[0], ' ', c[0])
b[0] = 33
print(a[0], ' ', c[0])
